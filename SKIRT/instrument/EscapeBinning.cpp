////////////////////////////////////////////////////////////////////

EscapeBinning::FrameLayout EscapeBinning::frameLayout() const
{
    // a single row of pixels with the bin index as axis value
    FrameLayout layout;
    layout.numPixelsX = numBins();
    layout.numPixelsY = 1;
    layout.centerX = 0.5 * (layout.numPixelsX - 1);
    return layout;
}

