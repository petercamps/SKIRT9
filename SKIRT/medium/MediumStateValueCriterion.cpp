#include "MediumStateValueCriterion.hpp"

////////////////////////////////////////////////////////////////////

void MediumStateValueCriterion::setupSelfAfter()
{
    ValueCriterion::setupSelfAfter();
    _selection.select(this, variable(), true);
}

////////////////////////////////////////////////////////////////////

bool MediumStateValueCriterion::changesIn(IterationHistory::Loop loop) const
{
    return _selection.changesIn(loop);
}

////////////////////////////////////////////////////////////////////

double MediumStateValueCriterion::value(int m) const
{
    return _selection.value(m);
}

////////////////////////////////////////////////////////////////////

double MediumStateValueCriterion::numberDensity(int m) const
{
    return _selection.numberDensity(m);
}

////////////////////////////////////////////////////////////////////

string MediumStateValueCriterion::fieldDescription() const
{
    return _selection.description();
}

