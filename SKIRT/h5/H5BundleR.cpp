#include "H5BundleR.hpp"
#include "H5Core.hpp"

////////////////////////////////////////////////////////////////////

H5BundleR::H5BundleR(std::int64_t handle, string path) : H5ObjectR(handle, "HDF5 bundle", std::move(path)) {}

////////////////////////////////////////////////////////////////////

vector<string> H5BundleR::getDatasetNames() const
{
    return H5Core::datasetNames(handle(), context());
}

////////////////////////////////////////////////////////////////////

bool H5BundleR::hasDataset(const string& name) const
{
    return H5Core::hasDataset(handle(), name);
}

////////////////////////////////////////////////////////////////////

H5DatasetR H5BundleR::getDataset(const string& name) const
{
    return H5DatasetR(H5Core::openDataset(handle(), name, context()), path() + "/" + name);
}

