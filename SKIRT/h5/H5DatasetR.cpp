#include "H5DatasetR.hpp"
#include "H5Core.hpp"

////////////////////////////////////////////////////////////////////

H5DatasetR::H5DatasetR(std::int64_t handle, string path) : H5ObjectR(handle, "HDF5 dataset", std::move(path)) {}

////////////////////////////////////////////////////////////////////

vector<size_t> H5DatasetR::shape() const
{
    return H5Core::shape(handle(), context());
}

////////////////////////////////////////////////////////////////////

vector<char> H5DatasetR::readBool() const
{
    return H5Core::readBool(handle(), context());
}

////////////////////////////////////////////////////////////////////

vector<int> H5DatasetR::readInt() const
{
    return H5Core::readInt(handle(), context());
}

////////////////////////////////////////////////////////////////////

Array H5DatasetR::readDouble() const
{
    return H5Core::readDouble(handle(), context());
}

